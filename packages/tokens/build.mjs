// Talus token build.
// Style Dictionary v4 reads the W3C token JSON in src/ and this script writes:
//   dist/talus.css   CSS variables named --talus-<path-joined-with-hyphens>
//   dist/tokens.ts   typed, resolved values for JS and the docs app
//
// Layering in the CSS:
//   :root                                      primitives, global, components
//   :root, [data-brand="enterprise"]           enterprise brand (the default)
//   :root, [data-brand="enterprise"][data-scheme="light"]  enterprise light colors (the default)
//   [data-brand="consumer"]                    consumer brand and consumer light colors
//   [data-brand="enterprise"][data-scheme="dark"]          enterprise dark colors
// Consumer has no dark mode yet, so consumer stays light whatever data-scheme says.
// Semantic tokens are written as var() references to primitive variables, never copied hex.

import StyleDictionary from "style-dictionary";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = (f) => path.join(here, "src", f);
const distDir = path.join(here, "dist");
fs.mkdirSync(distDir, { recursive: true });

// ---------- load and resolve through Style Dictionary ----------

async function loadCombo(brandFile, colorFile) {
  const sd = new StyleDictionary({
    source: [
      src("primitives.json"),
      src("global.json"),
      src(brandFile),
      src(colorFile),
      src("components.json"),
    ],
    platforms: { none: { transforms: [] } },
    log: { verbosity: "silent" },
  });
  await sd.hasInitialized;
  const tokens =
    typeof sd.getPlatformTokens === "function"
      ? await sd.getPlatformTokens("none")
      : await sd.exportPlatform("none");
  return tokens.tokens ?? tokens;
}

const entLight = await loadCombo("brand/enterprise.json", "color/enterprise-light.json");
const entDark = await loadCombo("brand/enterprise.json", "color/enterprise-dark.json");
const conLight = await loadCombo("brand/consumer.json", "color/consumer-light.json");

// ---------- walking helpers ----------

const isToken = (node) =>
  node && typeof node === "object" && ("$value" in node || "value" in node);

function* walk(node, trail = []) {
  if (!node || typeof node !== "object") return;
  if (isToken(node)) {
    yield { path: trail, token: node };
    return;
  }
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    yield* walk(child, [...trail, key]);
  }
}

const varName = (tokenPath) => `--talus-${tokenPath.join("-")}`;
const refToVar = (s) =>
  s.replace(/\{([^}]+)\}/g, (_, p) => `var(--talus-${p.split(".").join("-")})`);

const tokenValue = (t) => t.$value ?? t.value;
const tokenType = (t) => t.$type ?? t.type;
const originalValue = (t) => (t.original ? t.original.$value ?? t.original.value : undefined) ?? tokenValue(t);

function quoteFamily(name) {
  return /[^a-zA-Z-]/.test(name) ? `"${name}"` : name;
}

// CSS value from the ORIGINAL value, so references come out as var().
function cssValue(t) {
  const v = originalValue(t);
  const type = tokenType(t);
  if (typeof v === "string") return refToVar(v);
  if (typeof v === "number") return String(v);
  if (type === "fontFamily" && Array.isArray(v)) return v.map(quoteFamily).join(", ");
  if (type === "cubicBezier" && Array.isArray(v)) return `cubic-bezier(${v.join(", ")})`;
  if (type === "shadow") {
    const layers = Array.isArray(v) ? v : [v];
    return layers
      .map((l) =>
        [l.offsetX, l.offsetY, l.blur, l.spread, l.color]
          .map((part) => refToVar(String(part)))
          .join(" ")
      )
      .join(", ");
  }
  throw new Error(`No CSS rendering for token type ${type}: ${JSON.stringify(v)}`);
}

// Resolved value for tokens.ts. Shadows become finished CSS strings.
function tsValue(t) {
  const v = tokenValue(t);
  const type = tokenType(t);
  if (type === "shadow") {
    const layers = Array.isArray(v) ? v : [v];
    return layers
      .map((l) => [l.offsetX, l.offsetY, l.blur, l.spread, l.color].join(" "))
      .join(", ");
  }
  return v;
}

const fromFile = (suffix) => (entry) =>
  (entry.token.filePath ?? "").endsWith(suffix);

// ---------- dist/talus.css ----------

function cssBlock(selector, tree, fileSuffixes, { comment } = {}) {
  const lines = [];
  if (comment) lines.push(`/* ${comment} */`);
  lines.push(`${selector} {`);
  for (const suffix of fileSuffixes) {
    for (const entry of [...walk(tree)].filter(fromFile(suffix))) {
      lines.push(`  ${varName(entry.path)}: ${cssValue(entry.token)};`);
    }
  }
  lines.push(`}`);
  return lines.join("\n");
}

const motionVars = [...walk(entLight.motion, ["motion"])].map((e) => varName(e.path));

const css = [
  `/* Generated by packages/tokens/build.mjs. Do not edit by hand; edit src/ and rebuild. */`,
  cssBlock(":root", entLight, ["primitives.json", "global.json"], {
    comment: "Primitives and global tokens",
  }),
  cssBlock(':root,\n[data-brand="enterprise"]', entLight, ["brand/enterprise.json"], {
    comment: "Enterprise brand (default)",
  }),
  cssBlock(
    ':root,\n[data-brand="enterprise"][data-scheme="light"]',
    entLight,
    ["color/enterprise-light.json"],
    { comment: "Enterprise light colors (default)" }
  ),
  cssBlock('[data-brand="consumer"]', conLight, ["brand/consumer.json"], {
    comment: "Consumer brand",
  }),
  cssBlock('[data-brand="consumer"]', conLight, ["color/consumer-light.json"], {
    comment: "Consumer colors (light only; consumer has no dark mode yet)",
  }),
  cssBlock(
    '[data-brand="enterprise"][data-scheme="dark"]',
    entDark,
    ["color/enterprise-dark.json"],
    { comment: "Enterprise dark colors" }
  ),
  cssBlock(":root", entLight, ["components.json"], { comment: "Component tokens" }),
  [
    `/* Motion stops under prefers-reduced-motion */`,
    `@media (prefers-reduced-motion: reduce) {`,
    `  :root {`,
    ...motionVars.map((name) => `    ${name}: 0ms;`),
    `  }`,
    `}`,
  ].join("\n"),
].join("\n\n");

fs.writeFileSync(path.join(distDir, "talus.css"), css + "\n");

// ---------- dist/tokens.ts ----------

// Rebuild a nested plain object from one source file's tokens only. The merged
// tree mixes files under shared top-level keys (primitives and color modes both
// use "color"; primitives and brands both use "radius" and "font"), so tokens.ts
// slices by source file, not by key.
function filteredTree(tree, suffix, mapFn) {
  const out = {};
  for (const entry of [...walk(tree)].filter(fromFile(suffix))) {
    let node = out;
    for (const key of entry.path.slice(0, -1)) node = node[key] ??= {};
    node[entry.path.at(-1)] = mapFn(entry.token, entry.path);
  }
  return out;
}

function varsTree(node, trail = []) {
  if (isToken(node)) return `var(${varName(trail)})`;
  const out = {};
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    out[key] = varsTree(child, [...trail, key]);
  }
  return out;
}

const stringify = (obj) => JSON.stringify(obj, null, 2);

const primitivesTree = filteredTree(entLight, "primitives.json", tsValue);
const globalTree = filteredTree(entLight, "global.json", tsValue);
delete globalTree.elevation; // elevation shadows resolve per color mode below
const brandTree = {
  enterprise: filteredTree(entLight, "brand/enterprise.json", tsValue),
  consumer: filteredTree(conLight, "brand/consumer.json", tsValue),
};
const colorModesTree = {
  "enterprise-light": {
    color: filteredTree(entLight, "color/enterprise-light.json", tsValue).color,
    elevation: filteredTree(entLight, "global.json", tsValue).elevation,
  },
  "enterprise-dark": {
    color: filteredTree(entDark, "color/enterprise-dark.json", tsValue).color,
    elevation: filteredTree(entDark, "global.json", tsValue).elevation,
  },
  "consumer-light": {
    color: filteredTree(conLight, "color/consumer-light.json", tsValue).color,
    elevation: filteredTree(conLight, "global.json", tsValue).elevation,
  },
};

const ts = `// Generated by packages/tokens/build.mjs. Do not edit by hand; edit src/ and rebuild.
// Resolved token values plus the var() name of every CSS custom property.

export type Brand = "enterprise" | "consumer";
export type Scheme = "light" | "dark";
export type ColorMode = "enterprise-light" | "enterprise-dark" | "consumer-light";

export const brandNames: Brand[] = ["enterprise", "consumer"];
export const schemeNames: Scheme[] = ["light", "dark"];
export const colorModeNames: ColorMode[] = [
  "enterprise-light",
  "enterprise-dark",
  "consumer-light",
];

/** Every token path as a ready-to-use var() reference, e.g. vars.color.text.primary === "var(--talus-color-text-primary)". */
export const vars = ${stringify(varsTree(entLight))} as const;

/** Raw primitive values. Products use semantic tokens instead; these feed docs and tooling. */
export const primitives = ${stringify(primitivesTree)} as const;

/** Global tokens that are the same in every brand and color mode. */
export const global = ${stringify(globalTree)} as const;

/** Brand tokens (type, sizes, density, shape), resolved per brand. */
export const brand = ${stringify(brandTree)} as const;

/** Semantic colors and elevation shadows, resolved per color mode. */
export const colorModes = ${stringify(colorModesTree)} as const;
`;

fs.writeFileSync(path.join(distDir, "tokens.ts"), ts);

const varCount = [...walk(entLight)].length;
console.log(`talus.css and tokens.ts written (${varCount} tokens).`);
